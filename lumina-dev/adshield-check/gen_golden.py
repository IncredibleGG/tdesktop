def link_line(l):
    return "L" + "\t".join([l.token, l.type, l.kind, l.source, l.domain, "1" if l.shortener else "0"])


def extraction_canon(raw):
    f = A.fold(raw)
    ex = A.extract_links(f)
    lines = ["F" + f, "X" + ex.f_nolinks]
    lines += [link_line(l) for l in ex.links]
    lines += ["M" + m for m in ex.mentions]
    lines.append("P" + ("1" if ex.pointer else "0"))
    lines += ["N" + n for n in ex.long_numbers]
    lines += ["H" + h for h in sorted(A.leading_handles(f))]
    lines += ["G" + p for p in A.paragraphs(ex.f_nolinks)]
    for source in ("text", "hidden"):
        u = A.canonicalize_url(f, source)
        lines.append("U-" if u is None else "U" + link_line(u)[1:])
    return "\n".join(lines)


